'use strict';
const assert=require('node:assert/strict');
const {METHOD,requestData,inspectResponse}=require('./paymentresponse-lab.js');
const p={payeeVpa:'merchant@bank',payeeName:'Test Merchant',mcc:'5411',amount:'1.00',transactionRef:'ORDERTEST123',orderUrl:'https://example.org/test'};
const r=requestData(p);
assert.equal(r.methods[0].supportedMethods,METHOD);
assert.equal(r.methods[0].data.tr,p.transactionRef);
assert.equal(r.details.total.amount.value,'1.00');
assert.throws(()=>requestData({...p,mcc:''}),/INVALID_LAB/);
assert.throws(()=>requestData({...p,amount:'1.001'}),/INVALID_LAB/);
const inspect=details=>inspectResponse({methodName:METHOD,details},p);
let out=inspect({tezResponse:JSON.stringify({Status:'SUCCESS',amount:'1.00',toVpa:'merchant@bank',txnId:'123456789012',txnRef:'ORDERTEST123'}),signature:'unverified'});
assert.equal(out.result,'TEZ_RESPONSE_OBSERVED');
assert.equal(out.sessionCorrelated,true);
assert.equal(out.transactionIdFormat,'12_DIGIT');
assert.equal(out.googlePaySignaturePresent,true);
assert.equal(out.googlePaySignatureVerified,false);
assert.equal(out.bankRrnProven,false);
assert.equal(out.paymentVerified,false);
assert.equal(out.debitVerified,false);
out=inspect({tezResponse:JSON.stringify({Status:'SUCCESS',amount:'1.00',toVpa:'other@bank',txnId:'123456789012',txnRef:'ORDERTEST123'})});
assert.equal(out.sessionCorrelated,false);
assert.equal(out.evidenceState,'INCOMPLETE_OR_CONFLICTING_RETURN');
out=inspect({tezResponse:JSON.stringify({Status:'SUCCESS',amount:'1.00',toVpa:'merchant@bank',txnRef:'ORDERTEST123'})});
assert.equal(out.transactionIdPresent,false);
assert.equal(out.bankRrnProven,false);
assert.equal(inspect({tezResponse:'{broken'}).result,'MALFORMED_TEZ_RESPONSE');
assert.equal(inspectResponse({methodName:'basic-card',details:{}},p).result,'UNSUPPORTED_OR_UNEXPECTED_PAYMENT_METHOD');
console.log('PaymentResponse lab parser: 12 isolated tests passed; no real transaction performed.');
